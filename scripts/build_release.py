"""Build the FMODD single-file Windows release EXE.

Runs the whole release chain in dependency order, then verifies the artifact:

    python scripts\\build_release.py                 # full release build
    python scripts\\build_release.py --smoke-test    # build, then launch-check
    python scripts\\build_release.py --skip-native   # reuse existing native DLLs

The version comes from `PRODUCT_VERSION` in `src/fm_odds_web.py`, so bumping
the release means editing that one constant. Nothing here is committed: every
output lands in the gitignored `src/build/` or `dist/`.

What this reproduces is the observable packaging layout of the shipped
`FMODD-V2.x.exe`: one file, windowed, bundled `python3xx.dll`, `tools/*.dll`
and `desktop_host/`. What it cannot reproduce is the maintainer's private
protection chain (Cython `.pyd` modules and the signed integrity manifest),
which is absent from the published source.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
SRC = REPO / "src"
BUILD = SRC / "build"
PACKAGING = Path(__file__).resolve().parent / "packaging"
DESKTOP_HOST_DIR = BUILD / "desktop_host"
DIST = REPO / "dist"
VENV = BUILD / "release-venv"
PYINSTALLER_WORK = BUILD / "pyinstaller"
CSC = Path(r"C:\Windows\Microsoft.NET\Framework64\v4.0.30319\csc.exe")
VSWHERE = Path(r"C:\Program Files (x86)\Microsoft Visual Studio\Installer\vswhere.exe")

VERSION_SOURCE = SRC / "fm_odds_web.py"
VERSION_PATTERN = re.compile(r'^PRODUCT_VERSION\s*=\s*"([^"]+)"', re.MULTILINE)


class BuildError(RuntimeError):
    """A release step failed and the build must stop."""


def step(message: str) -> None:
    print(f"\n=== {message} ===", flush=True)


def run(command: list[str], *, cwd: Path = REPO, env: dict[str, str] | None = None) -> None:
    print("  $ " + subprocess.list2cmdline(command), flush=True)
    result = subprocess.run(command, cwd=str(cwd), env=env)
    if result.returncode:
        raise BuildError(f"command failed with exit code {result.returncode}: {command[0]}")


# ---------------------------------------------------------------- versioning


def read_product_version() -> str:
    """Return the shipped product version, for example ``V2.7.0beta``."""
    try:
        text = VERSION_SOURCE.read_text(encoding="utf-8")
    except OSError as error:
        raise BuildError(f"cannot read {VERSION_SOURCE}: {error}") from error
    match = VERSION_PATTERN.search(text)
    if match is None:
        raise BuildError(f"PRODUCT_VERSION is missing from {VERSION_SOURCE}")
    return match.group(1)


def split_version(product_version: str) -> tuple[str, tuple[int, int, int, int], str]:
    """Split ``V2.7.0beta`` into the file name, numeric tuple and label."""
    label = product_version.lstrip("Vv")
    numbers = re.match(r"(\d+)\.(\d+)\.(\d+)", label)
    if numbers is None:
        raise BuildError(f"unrecognised version {product_version!r}; expected V<major>.<minor>.<patch>")
    tuple_ = (int(numbers.group(1)), int(numbers.group(2)), int(numbers.group(3)), 0)
    return f"FMODD-{product_version}", tuple_, label


def write_version_resource(path: Path, tuple_: tuple[int, int, int, int], label: str, name: str) -> None:
    """Generate the Windows version resource PyInstaller embeds."""
    joined = ", ".join(str(part) for part in tuple_)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        f"""# Generated by scripts/build_release.py. Do not edit manually.
VSVersionInfo(
  ffi=FixedFileInfo(
    filevers=({joined}),
    prodvers=({joined}),
    mask=0x3f,
    flags=0x0,
    OS=0x40004,
    fileType=0x1,
    subtype=0x0,
    date=(0, 0)
  ),
  kids=[
    StringFileInfo([
      StringTable('040904B0', [
        StringStruct('CompanyName', 'FMODD'),
        StringStruct('FileDescription', 'Football Manager local odds tool'),
        StringStruct('FileVersion', '{label}'),
        StringStruct('InternalName', 'FMODD'),
        StringStruct('LegalCopyright', 'FMODD'),
        StringStruct('OriginalFilename', '{name}.exe'),
        StringStruct('ProductName', 'FMODD'),
        StringStruct('ProductVersion', '{label}')
      ])
    ]),
    VarFileInfo([VarStruct('Translation', [1033, 1200])])
  ]
)
""",
        encoding="utf-8",
        newline="\n",
    )


# ------------------------------------------------------------------- python


def ensure_pyinstaller(use_venv: bool) -> Path:
    """Return an interpreter that can import PyInstaller.

    The build needs PyInstaller plus a Python that can import the application
    sources. Rather than mutate the developer's environment, a dedicated venv
    under the gitignored ``src/build/`` is created on first use.
    """
    if not use_venv:
        try:
            import PyInstaller  # noqa: F401
        except ImportError as error:
            raise BuildError(
                "PyInstaller is not installed for this interpreter; "
                "install it or drop --no-venv to let the script create one"
            ) from error
        return Path(sys.executable)

    python = VENV / "Scripts" / "python.exe"
    if not python.is_file():
        step("Creating the release venv")
        VENV.parent.mkdir(parents=True, exist_ok=True)
        run([sys.executable, "-m", "venv", str(VENV)])
    probe = subprocess.run(
        [str(python), "-c", "import PyInstaller"], capture_output=True, text=True,
    )
    if probe.returncode:
        step("Installing PyInstaller into the release venv")
        run([str(python), "-m", "pip", "install", "--upgrade", "pip", "pyinstaller"])
    return python


# -------------------------------------------------------------- build steps


def build_rust_native() -> None:
    step("Building the Rust native core")
    run([sys.executable, str(REPO / "scripts" / "build_rust_native.py")])


def build_cpp_hook_core() -> None:
    step("Building the C++ Hook core")
    if not VSWHERE.is_file():
        raise BuildError(
            "Visual Studio C++ x64 build tools are required: vswhere.exe is missing"
        )
    run([sys.executable, str(REPO / "scripts" / "build_cpp_hook_core.py")])


def restore_webview2() -> None:
    step("Restoring the pinned WebView2 SDK")
    run([sys.executable, str(REPO / "scripts" / "restore_webview2.py")])


def build_desktop_host() -> Path:
    """Compile FMODD.WebViewHost.exe with the system .NET Framework compiler.

    ``dotnet build src\\desktop\\WebViewHost.csproj`` needs the net48 targeting
    pack, which is not installed on every build machine. The system csc.exe
    compiles the same WinForms host without it.
    """
    step("Compiling the WebView2 desktop host")
    if not CSC.is_file():
        raise BuildError(f"the .NET Framework compiler is missing: {CSC}")
    output = DESKTOP_HOST_DIR / "FMODD.WebViewHost.exe"
    DESKTOP_HOST_DIR.mkdir(parents=True, exist_ok=True)
    run([
        str(CSC), "/nologo", "/target:winexe", "/optimize+", "/codepage:65001",
        f"/out:{output}",
        f"/win32manifest:{SRC / 'desktop' / 'FMODD.manifest'}",
        f"/win32icon:{SRC / 'assets' / 'desktop' / 'fmodd.ico'}",
        "/r:System.dll", "/r:System.Core.dll", "/r:System.Drawing.dll",
        "/r:System.Windows.Forms.dll", "/r:System.Net.dll", "/r:System.Runtime.dll",
        f"/r:{DESKTOP_HOST_DIR / 'Microsoft.Web.WebView2.Core.dll'}",
        f"/r:{DESKTOP_HOST_DIR / 'Microsoft.Web.WebView2.WinForms.dll'}",
        str(SRC / "desktop" / "WebViewHost.cs"),
    ])
    if not output.is_file():
        raise BuildError(f"the desktop host was not produced: {output}")
    return output


def build_embedded_web_assets() -> None:
    step("Embedding the web assets")
    run([sys.executable, str(SRC / "tools" / "build_embedded_web_assets.py")])


def run_pyinstaller(python: Path, name: str, version_file: Path) -> Path:
    step("Packaging the single-file EXE")
    environment = os.environ.copy()
    environment["FMODD_RELEASE_NAME"] = name
    environment["FMODD_RELEASE_VERSION_FILE"] = str(version_file)
    environment["PYTHONUTF8"] = "1"
    DIST.mkdir(parents=True, exist_ok=True)
    run([
        str(python), "-m", "PyInstaller", str(PACKAGING / "FMODD.spec"),
        "--noconfirm", "--distpath", str(DIST), "--workpath", str(PYINSTALLER_WORK),
    ], env=environment)
    artifact = DIST / f"{name}.exe"
    if not artifact.is_file():
        raise BuildError(f"PyInstaller did not produce {artifact}")
    return artifact


# ---------------------------------------------------------------- reporting


def windows_file_version(path: Path) -> str | None:
    try:
        import ctypes
        from ctypes import wintypes
    except ImportError:
        return None
    version = ctypes.WinDLL("version", use_last_error=True)
    version.GetFileVersionInfoSizeW.argtypes = [wintypes.LPCWSTR, ctypes.POINTER(wintypes.DWORD)]
    version.GetFileVersionInfoSizeW.restype = wintypes.DWORD
    version.GetFileVersionInfoW.argtypes = [
        wintypes.LPCWSTR, wintypes.DWORD, wintypes.DWORD, ctypes.c_void_p,
    ]
    version.GetFileVersionInfoW.restype = wintypes.BOOL
    version.VerQueryValueW.argtypes = [
        ctypes.c_void_p, wintypes.LPCWSTR, ctypes.POINTER(ctypes.c_void_p),
        ctypes.POINTER(wintypes.UINT),
    ]
    version.VerQueryValueW.restype = wintypes.BOOL

    ignored = wintypes.DWORD()
    size = int(version.GetFileVersionInfoSizeW(str(path), ctypes.byref(ignored)))
    if not size:
        return None
    buffer = ctypes.create_string_buffer(size)
    if not version.GetFileVersionInfoW(str(path), 0, size, buffer):
        return None
    pointer = ctypes.c_void_p()
    length = wintypes.UINT()
    if not version.VerQueryValueW(
        buffer, "\\StringFileInfo\\040904B0\\FileVersion",
        ctypes.byref(pointer), ctypes.byref(length),
    ):
        return None
    return ctypes.wstring_at(pointer.value, length.value).rstrip("\x00")


def archive_entries(python: Path, artifact: Path) -> set[str] | None:
    """List the bundled archive entries, or ``None`` if it cannot be read.

    The reader lives in PyInstaller, which is installed in the release venv
    rather than in whatever interpreter runs this script, so the probe runs in
    the PyInstaller interpreter. Returning ``None`` means "unknown", which the
    caller reports as a failure instead of silently passing.
    """
    probe = (
        "import json, sys\n"
        "from PyInstaller.archive.readers import CArchiveReader\n"
        "print(json.dumps(list(CArchiveReader(sys.argv[1]).toc)))\n"
    )
    try:
        result = subprocess.run(
            [str(python), "-c", probe, str(artifact)],
            capture_output=True, text=True,
        )
    except OSError as error:
        print(f"  note: archive probe could not start: {error}", flush=True)
        return None
    if result.returncode:
        print(f"  note: archive probe failed: {result.stderr.strip()[:200]}", flush=True)
        return None
    try:
        return {entry.replace("/", "\\") for entry in json.loads(result.stdout)}
    except json.JSONDecodeError:
        return None


def describe_artifact(artifact: Path, expected: str, python: Path) -> list[str]:
    """Check size, embedded version resource and bundled payload."""
    problems: list[str] = []
    size_mb = artifact.stat().st_size / (1024 * 1024)
    if size_mb < 50:
        problems.append(f"unexpectedly small artifact: {size_mb:.1f} MB")

    version = windows_file_version(artifact)
    if version is None:
        problems.append("the version resource could not be read")
    elif version != expected:
        problems.append(f"version resource is {version!r}, expected {expected!r}")

    required = (
        "desktop_host/FMODD.WebViewHost.exe",
        "desktop_host/WebView2Loader.dll",
        "tools/fmodd_native_core.dll",
        "tools/fmodd_hook_core.dll",
        "web/index.html",
        "web/app.js",
    )
    entries = archive_entries(python, artifact)
    if entries is None:
        problems.append("the bundled payload could not be inspected")
    else:
        for relative in required:
            if relative.replace("/", "\\") not in entries:
                problems.append(f"bundled payload is missing: {relative}")
    return problems


def smoke_test(artifact: Path) -> None:
    """Launch the artifact, wait for the local service and stop it again.

    This only proves the packaging is coherent. It never connects to Football
    Manager and therefore says nothing about live-game behaviour.
    """
    step("Smoke test: launching the packaged EXE")
    import time
    import urllib.error
    import urllib.request

    process = subprocess.Popen(
        [str(artifact)], cwd=str(DIST),
        stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
    )
    try:
        deadline = time.monotonic() + 90
        url = "http://127.0.0.1:7856/"
        while time.monotonic() < deadline:
            if process.poll() is not None:
                raise BuildError(
                    f"the EXE exited during startup with code {process.returncode}; "
                    "run it in a console build to see the traceback"
                )
            try:
                with urllib.request.urlopen(url, timeout=3) as response:
                    if response.status == 200:
                        print(f"  local service answered {url} with 200", flush=True)
                        return
            except (urllib.error.URLError, OSError):
                time.sleep(2)
        raise BuildError("the local service did not answer within 90 seconds")
    finally:
        if process.poll() is None:
            process.terminate()
            try:
                process.wait(timeout=15)
            except subprocess.TimeoutExpired:
                process.kill()
                process.wait(timeout=15)
        # The WebView2 host is started as a child process; stop any survivor.
        subprocess.run(
            ["taskkill", "/F", "/IM", "FMODD.WebViewHost.exe"],
            capture_output=True, check=False,
        )


def main() -> int:
    parser = argparse.ArgumentParser(description="Build the FMODD single-file release EXE.")
    parser.add_argument(
        "--skip-native", action="store_true",
        help="reuse the existing Rust/C++ DLLs instead of rebuilding them",
    )
    parser.add_argument(
        "--no-venv", action="store_true",
        help="use the current interpreter's PyInstaller instead of src/build/release-venv",
    )
    parser.add_argument(
        "--smoke-test", action="store_true",
        help="launch the artifact after building and wait for the local service",
    )
    args = parser.parse_args()

    if os.name != "nt":
        raise BuildError("the FMODD runtime is Windows-only")

    product_version = read_product_version()
    name, tuple_, label = split_version(product_version)
    print(f"FMODD release {product_version} -> dist/{name}.exe", flush=True)

    if not args.skip_native:
        build_rust_native()
        build_cpp_hook_core()
    restore_webview2()
    build_desktop_host()
    build_embedded_web_assets()

    version_file = BUILD / "FMODD.version"
    write_version_resource(version_file, tuple_, label, name)

    python = ensure_pyinstaller(use_venv=not args.no_venv)
    artifact = run_pyinstaller(python, name, version_file)

    step("Verifying the artifact")
    problems = describe_artifact(artifact, label, python)
    if problems:
        for problem in problems:
            print(f"  FAIL {problem}", flush=True)
        raise BuildError("the artifact did not pass verification")

    if args.smoke_test:
        smoke_test(artifact)

    size_mb = artifact.stat().st_size / (1024 * 1024)
    print(
        f"\nRelease ready: {artifact}\n"
        f"  version : {label}\n"
        f"  size    : {size_mb:.1f} MB\n"
        f"  payload : verified (desktop_host, native DLLs, web assets)\n"
        "\nThis is a local build, not an official release artifact: it carries no\n"
        "Cython protection and its integrity checking is a no-op.\n",
        flush=True,
    )
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except BuildError as error:
        print(f"\nBUILD FAILED: {error}", file=sys.stderr)
        raise SystemExit(1)
